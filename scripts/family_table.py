#!/usr/bin/env python3
"""Summary table of the configuration families (one representative run each), B0 and T_e first.

    python scripts/family_table.py            # markdown to stdout
    python scripts/family_table.py --md runs/FAMILY_SUMMARY.md --csv runs/FAMILY_SUMMARY.csv

Every number is derived from the run's config.yaml through kinshock.units.derive, so the table
cannot drift from what the decks ran. Columns follow the shock workbook's families:
47 keV = "Inflated Te" (reduce m_i), 470 eV = "Reduced ME", Inflated m_e (PSC's convention at
real c), RMR = real mass ratio, deflated T_e (vA_lowTab) and deflated B (mb_r100).
The false-shock row is the user's by-eye verdict (RESULTS 2026-10-12).
"""
from __future__ import annotations

import argparse
import csv
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "src"))

import kinshock  # noqa: E402
from kinshock import units  # noqa: E402

# (column label, run dir under runs/, how mu is reached, false-shock verdict)
FAMILIES = [
    ("47 keV", "E_phase/ek_47keV_t2", "light ion", "clean"),
    ("470 eV", "R1_phase/R1_470eV_s3f8_t2", "light ion", "notch (after 0.3)"),
    ("Inflated m_e 470 eV", "IM_phase/im_470eV_t03", "heavy electron", "notch (by 0.3)"),
    ("Inflated m_e 47 keV", "IM_phase/im_47keV_t03", "heavy electron", "clean"),
    ("RMR 470 eV", "U_phase/um1836_470eV", "real (1836)", "notch (by 0.3)"),
    ("RMR 47 keV", "U_phase/um1836_47keV", "real (1836)", "clean"),
    ("Deflated T_e", "V_phase/vA_lowTab", "light ion", "notch (by 0.3)"),
    ("Deflated B", "M_phase/mb_r100", "light ion", "no movie (twin mb_r100_t2: clean)"),
    ("PoC twin", "PoC_phase/poc1d_twin", "light ion", "notch"),
    ("PoC resolved", "PoC_phase/poc1d_resolved", "light ion", "notch"),
]

MD_HEADER = """# Configuration families — summary table

Generated by `scripts/family_table.py --md runs/FAMILY_SUMMARY.md --csv runs/FAMILY_SUMMARY.csv`
from each representative run's `config.yaml` (regenerate, don't hand-edit). B₀ and T_e come
first. Columns follow the shock workbook's families: 47 keV = "Inflated Te" (μ = 100 by a light
ion), 470 eV = "Reduced ME", Inflated mₑ = PSC's convention at real c, RMR = real mass ratio,
Deflated T_e = `vA_lowTab`, Deflated B = `mb_r100` (47 keV with B₀ lowered 10×), and the two
PoC_phase runs (1D twins of the collaborator's 2D CH-plasma surrogate). The last row is the
user's by-eye false-shock verdict (RESULTS 2026-10-12).
"""

MD_NOTES = """
**Read with these in mind.**
- **The two RMR runs are not resolution-matched.** `um1836_470eV` is at dz/λ_D 6.07
  (N_D 16), while every other column is at 0.38–0.76. Its notch therefore cannot be told apart
  from the coarse-grid onset (RESULTS 2026-10-12).
- **Deflated B (`mb_r100`) has no phase-space movie of its own.** Its long twin `mb_r100_t2`
  (same physics, dz/λ_D 0.758 with shape 3 + filter 8, to t·ω_ci0 = 2.0) was judged clean.
- **The Inflated mₑ runs and `mb_r100` only reach t·ω_ci0 = 0.3.** A "clean" there means
  clean to that time.
- **The PoC runs notch at ε₀ = 0.032 on fine grids** (dz/λ_D 1.30 and 0.35, N_D 790 and
  2,900). That ε₀ lies between `im_47keV_t03` (0.010) and the 47 keV runs (0.044), which are all
  clean, so **ε₀ alone does not separate notch from clean**, and the PoC notch is not
  resolution. The PoC plasma differs from every other column in several ways at once: Z = 3.5,
  an applied B₀(z) gradient, n_target/n_e0 = 400 vs 250, n_e 10⁸× lower, and **M_A 6.4**. The
  only other notching run outside the low-ε₀ 470 eV group is `vA_lowTab`, also at low M_A
  (3.3). Every M_A ≥ 14 run at ε₀ ≥ 0.010 is clean. That is a correlation across two runs
  that differ in many other ways, not a test.
"""


def _num(x):
    """Plain number: thousands separators at >= 1000, 3 significant figures below."""
    return f"{x:,.0f}" if abs(x) >= 1000 else f"{x:.3g}"


def quantities(run_rel):
    cfg = kinshock.load(os.path.join(ROOT, "runs", run_rel))
    sc = units.derive(cfg)
    C, QE, EPS0 = units.C, units.QE, units.EPS0
    T0 = cfg["plasma"]["ambient"]["theta_0"] * sc.me * C ** 2 / QE
    vte0 = math.sqrt(T0 * QE / sc.me)
    lamD0 = math.sqrt(EPS0 * T0 / (sc.namb * QE))
    wpe0 = math.sqrt(sc.namb * QE ** 2 / (EPS0 * sc.me))
    wce0 = QE * sc.B0 / sc.me
    ppc = cfg["numerics"]["ppc"]["ambient"]
    t_end = int(cfg["numerics"]["max_step"]) / sc.steps_per_wci0
    prof = units.field_profile(cfg) if hasattr(units, "field_profile") else None
    bprof = ("uniform" if prof is None else
             f"B0/(1+abs(z)/{prof['L'] / sc.di0:.2f} d_i0), floor {prof['floor'] / prof['B0']:.3g} B0")
    return [
        ("B0 [T] (at z = 0)", f"{sc.B0:.3g}"),
        ("B0 profile", bprof),
        ("T_e,ab [eV]", _num(sc.Te_ab_eV)),
        ("T_0 upstream [eV]", _num(T0)),
        ("m_i/m_e (mu)", f"{sc.mi / sc.me:.0f}"),
        ("m_e / m_e,real", f"{sc.me / units.ME:.4g}"),
        ("ion charge Z", f"{cfg['reference'].get('charge_state', 1):g}"),
        ("n_target / n_e0", f"{sc.nt / sc.namb:.0f}"),
        ("n_e,ab [m^-3]", f"{sc.n0:.2e}"),
        ("n_e0 upstream [m^-3]", f"{sc.namb:.2e}"),
        ("eps_ab = v_te,ab/c", f"{sc.vte_ab / C:.4f}"),
        ("eps_0 = v_te,0/c", f"{vte0 / C:.5f}"),
        ("v_sh (model) [km/s]", _num(sc.vsh_model / 1e3)),
        ("v_A [km/s]", _num(sc.vA / 1e3)),
        ("M_A", f"{sc.MA:.2f}"),
        ("M_ms", f"{sc.Mms:.2f}"),
        ("beta_ab", _num(sc.beta_ab)),
        ("beta_0", f"{sc.beta_0:.3g}"),
        ("w_pe0 / w_ce0", f"{wpe0 / wce0:.3g}"),
        ("d_i0 [mm]", _num(sc.di0 * 1e3)),
        ("1/w_ci0 [ns]", f"{1e9 / sc.wci0:.4g}"),
        ("dz / lambda_D,0", f"{sc.dz / lamD0:.3f}"),
        ("N_D = ppc lambda_D/dz", f"{ppc * lamD0 / sc.dz:.0f}"),
        ("runs to t*w_ci0", f"{t_end:.2f}"),
    ]


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--csv", default=None)
    ap.add_argument("--md", default=None, help="write the full markdown page (header, table, notes)")
    args = ap.parse_args()

    cols = [(label, run, how, verdict, quantities(run)) for label, run, how, verdict in FAMILIES]
    names = [k for k, _ in cols[0][4]]
    rows = [["run"] + [f"`{run.split('/')[1]}`" for _, run, _, _, _ in cols],
            ["mu reached by"] + [how for _, _, how, _, _ in cols]]
    rows += [[n] + [dict(q)[n] for *_, q in cols] for n in names]
    rows += [["false shock (by eye)"] + [v for _, _, _, v, _ in cols]]
    header = ["quantity"] + [label for label, *_ in cols]
    table = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    table += ["| " + " | ".join(r) + " |" for r in rows]
    print("\n".join(table))
    if args.md:
        with open(args.md, "w") as fh:
            fh.write(MD_HEADER + "\n" + "\n".join(table) + "\n" + MD_NOTES)
        print(f"\nwrote {args.md}", file=sys.stderr)
    if args.csv:
        with open(args.csv, "w", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(header)
            for r in rows:
                w.writerow([c.strip("`") for c in r])
        print(f"\nwrote {args.csv}", file=sys.stderr)


if __name__ == "__main__":
    main()
